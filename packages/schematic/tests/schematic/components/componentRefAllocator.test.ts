import { fixtureDocument } from "../support/fixtureDocument";
import { describe, expect, it } from "vitest";
import { ComponentRefAllocator, isAutoGeneratedComponentRef } from "../../../src/schematic/componentRefAllocator";
import type { ComponentInstance, ComponentType, SchematicDocument } from "../../../src/schematic/types";

function component(type: ComponentType, ref: string): ComponentInstance {
  return {
    id: `${type}-${ref}`,
    type,
    ref,
    x: 0,
    y: 0,
    rotation: 0,
    mirrored: false,
    values: { main: ref }
  };
}

function document(components: ComponentInstance[]): SchematicDocument {
  return fixtureDocument({

    junctionAppearances: [],
    netLabels: [],
    notes: [], components, wires: [], junctions: [] });
}

describe("schematic component ref allocator", () => {
  it("distinguishes exact generated refs from custom names", () => {
    expect(isAutoGeneratedComponentRef(component("resistor", "R1"))).toBe(true);
    expect(isAutoGeneratedComponentRef(component("ota", "Gm42"))).toBe(true);
    expect(isAutoGeneratedComponentRef(component("resistor", "Rfb"))).toBe(false);
    expect(isAutoGeneratedComponentRef(component("resistor", "R1extra"))).toBe(false);
    expect(isAutoGeneratedComponentRef(component("resistor", "1"))).toBe(false);
  });

  it("allocates fresh refs from component prefixes and labels", () => {
    const allocator = new ComponentRefAllocator();

    expect(allocator.next("resistor")).toBe("R1");
    expect(allocator.next("resistor")).toBe("R2");
    expect(allocator.next("capacitor")).toBe("C1");
    expect(allocator.next("gnd")).toBe("GND1");
    expect(allocator.next("vdd")).toBe("VDD1");
  });

  it("shares counters for component types with the same value prefix", () => {
    const allocator = new ComponentRefAllocator();

    expect(allocator.next("nmos")).toBe("M1");
    expect(allocator.next("pmos")).toBe("M2");
    expect(allocator.next("npn")).toBe("Q1");
    expect(allocator.next("pnp")).toBe("Q2");
    expect(allocator.next("ota")).toBe("Gm1");
    expect(allocator.next("diffOta")).toBe("Gm2");
    expect(allocator.next("gm")).toBe("Gm3");
    expect(allocator.next("inverter")).toBe("X1");
    expect(allocator.next("digitalBuffer")).toBe("X2");
    expect(allocator.next("analogBuffer")).toBe("X3");
    expect(allocator.next("amp")).toBe("A1");
    expect(allocator.next("and")).toBe("AND1");
    expect(allocator.next("nand")).toBe("NAND1");
    expect(allocator.next("or")).toBe("OR1");
    expect(allocator.next("nor")).toBe("NOR1");
    expect(allocator.next("xor")).toBe("XOR1");
    expect(allocator.next("xnor")).toBe("XNOR1");
    expect(allocator.next("dff")).toBe("DFF1");
  });

  it("rebuilds counters from numeric refs and ignores custom nonnumeric refs", () => {
    const allocator = new ComponentRefAllocator();
    allocator.rebuild(document([
      component("resistor", "R12"),
      component("resistor", "Rcustom"),
      component("capacitor", "C3"),
      component("gnd", "GND2")
    ]));

    expect(allocator.next("resistor")).toBe("R13");
    expect(allocator.next("capacitor")).toBe("C4");
    expect(allocator.next("gnd")).toBe("GND3");
  });

  it("rebuilds shared-prefix counters from the maximum matching ref", () => {
    const allocator = new ComponentRefAllocator();
    allocator.rebuild(document([
      component("nmos", "M3"),
      component("pmos", "M8"),
      component("ota", "Gm2"),
      component("diffOta", "Gm5")
    ]));

    expect(allocator.next("nmos")).toBe("M9");
    expect(allocator.next("diffOta")).toBe("Gm6");
  });

  it("rebuild resets prior allocator state to the document state", () => {
    const allocator = new ComponentRefAllocator();
    allocator.next("resistor");
    allocator.next("resistor");

    allocator.rebuild(document([component("capacitor", "C7")]));

    expect(allocator.next("resistor")).toBe("R1");
    expect(allocator.next("capacitor")).toBe("C8");
  });

  it("avoids names already used in a sheet when allocating copied instances", () => {
    const allocator = new ComponentRefAllocator();
    allocator.rebuild(document([
      component("sheetBlock", "X2"),
      component("sheetBlock", "x3"),
      component("resistor", "X4")
    ]));
    expect(allocator.next("sheetBlock")).toBe("X5");
    expect(allocator.next("inverter")).toBe("X6");
  });
});
