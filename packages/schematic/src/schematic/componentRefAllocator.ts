import { getComponentDef } from "./catalog";
import { rebuildComponentRefCounters } from "./document/documentModel";
import type { ComponentInstance, ComponentType, SchematicDocument } from "./types";

export function componentRefPrefix(type: ComponentType) {
  const def = getComponentDef(type);
  return def.valuePrefix ?? def.label;
}

export function isAutoGeneratedComponentRef(component: Pick<ComponentInstance, "type" | "ref">) {
  const prefix = componentRefPrefix(component.type);
  if (!component.ref.startsWith(prefix)) return false;
  return /^\d+$/.test(component.ref.slice(prefix.length));
}

export class ComponentRefAllocator {
  private readonly counters = new Map<string, number>();

  next(type: ComponentType) {
    const prefix = componentRefPrefix(type);
    const index = (this.counters.get(prefix) ?? 0) + 1;
    this.counters.set(prefix, index);
    return `${prefix}${index}`;
  }

  rebuild(document: SchematicDocument) {
    this.counters.clear();
    rebuildComponentRefCounters(document).forEach((value, key) => this.counters.set(key, value));
  }
}
