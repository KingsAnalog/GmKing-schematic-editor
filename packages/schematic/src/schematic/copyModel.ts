export type CopySource = SymbolTemplateContext & {
  connections: SchematicConnections;
  components: ComponentInstance[];
  wires: Wire[];
  inductorCouplings?: InductorCoupling[];
  netLabels: NetLabel[];
  notes: SchematicNote[];
  junctionAppearances: JunctionAppearance[];
};

export type CopyState = {
  source: CopySource;
  anchor: Point;
};

type BuildCopySourceInput = SymbolTemplateContext & {
  connections: SchematicConnections;
  components: ComponentInstance[];
  wires: Wire[];
  inductorCouplings?: InductorCoupling[];
  netLabels: NetLabel[];
  notes: SchematicNote[];
  junctionPoints: Point[];
  junctionKeys: Set<string>;
  junctionAppearances: JunctionAppearance[];
};

type InstantiateCopyOptions = {
  preview: boolean;
  nextComponentRef: (type: ComponentType) => string;
  createId: () => string;
};

export type CopyPlacementResult = {
  count: number;
  ids: string[];
  noteIds: string[];
  status: string;
  placed: boolean;
};

export function buildCopySource(input: BuildCopySourceInput): CopySource {
  const selectedComponentIds = new Set(input.components.map((component) => component.id));
  const selectedWireIds = new Set(input.wires.map((wire) => wire.id));
  const selectedWirePaths = input.wires.map((wire) => clonePoints(wire.points));
  const relatedAppearances = input.junctionAppearances.filter((appearance) => {
    const point = snapPoint(appearance.point);
    return input.junctionKeys.has(pointKey(point)) || selectedWirePaths.some((path) => pointOnPath(point, path));
  });
  return {
    symbolTemplate: resolveSymbolTemplate(input.symbolTemplate).id,
    components: input.components.map((component) => cloneComponent(component)),
    wires: input.wires.map((wire) => cloneWire(wire)),
    connections: selectConnections(input.connections, selectedComponentIds, selectedWireIds),
    inductorCouplings: (input.inductorCouplings ?? [])
      .filter((coupling) =>
        selectedComponentIds.has(coupling.inductorAId)
        && selectedComponentIds.has(coupling.inductorBId)
      )
      .map(cloneInductorCoupling),
    netLabels: input.netLabels.map((label) => {
      const cloned = cloneNetLabel(label);
      if (!selectedWireIds.has(cloned.attachment.wireId)) cloned.attachment.wireId = "";
      return cloned;
    }),
    notes: input.notes.map((note) => cloneNote(note)),
    junctionAppearances: normalizeJunctionAppearances(
      relatedAppearances.map((appearance) => cloneJunctionAppearance(appearance))
    )
  };
}

export function copySourceFromDocument(document: SchematicDocument): CopySource {
  return {
    symbolTemplate: resolveSymbolTemplate(document.symbolTemplate).id,
    connections: cloneConnections(document.connections),
    components: document.components.map(cloneComponent),
    wires: document.wires.map(cloneWire),
    inductorCouplings: (document.inductorCouplings ?? []).map(cloneInductorCoupling),
    netLabels: document.netLabels.map(cloneNetLabel),
    notes: document.notes.map(cloneNote),
    junctionAppearances: document.junctionAppearances.map(cloneJunctionAppearance)
  };
}

export function copySourceBounds(source: CopySource) {
  return unionRects([
    ...source.components.map(componentVisualBounds),
    ...source.wires.map((wire) => wireVisualBounds(wire)),
    ...source.netLabels.map(netLabelVisualBounds),
    ...source.notes.map(noteVisualBounds)
  ]);
}

export function copySourceCenterAnchor(source: CopySource): Point | null {
  const bounds = copySourceBounds(source);
  if (!bounds) return null;
  return snapPoint({
    x: bounds.x + bounds.width / 2,
    y: bounds.y + bounds.height / 2
  });
}

export function instantiateCopyAt(copyState: CopyState | null, point: Point, options: InstantiateCopyOptions): CopySource {
  if (!copyState) return emptyCopySource();
  const target = snapPoint(point);
  const delta = {
    x: target.x - copyState.anchor.x,
    y: target.y - copyState.anchor.y
  };
  const movePoint = (source: Point) => snapPoint({ x: source.x + delta.x, y: source.y + delta.y });
  const components = copyState.source.components.map((component, index) => {
    const reallocateRef = !options.preview && isAutoGeneratedComponentRef(component);
    const ref = reallocateRef ? options.nextComponentRef(component.type) : component.ref;
    const values = { ...component.values };
    const valueKey = resolveComponentDef(component).valueKey;
    if (valueKey === "main" && reallocateRef && ref !== component.ref && values.main === component.ref) values.main = ref;
    const moved = movePoint(component);
    return {
      ...cloneComponent(component),
      id: options.preview ? `copy-preview-component-${index}` : options.createId(),
      ref,
      x: moved.x,
      y: moved.y,
      values
    };
  });
  const copiedComponentIds = new Map(
    copyState.source.components.map((component, index) => [component.id, components[index]?.id])
  );
  const inductorCouplings = (copyState.source.inductorCouplings ?? []).flatMap((coupling, index) => {
    const inductorAId = copiedComponentIds.get(coupling.inductorAId);
    const inductorBId = copiedComponentIds.get(coupling.inductorBId);
    if (!inductorAId || !inductorBId) return [];
    return [{
      ...cloneInductorCoupling(coupling),
      id: options.preview ? `copy-preview-coupling-${index}` : options.createId(),
      inductorAId,
      inductorBId
    }];
  });
  const wires = copyState.source.wires.map((wire, index) => ({
    ...cloneWire(wire),
    id: options.preview ? `copy-preview-wire-${index}` : options.createId(),
    points: normalizeWirePath(wire.points.map(movePoint))
  }));
  const copiedWireIds = new Map(copyState.source.wires.map((wire, index) => [wire.id, wires[index]?.id]));
  const netLabels = copyState.source.netLabels.map((label, index) => ({
    ...cloneNetLabel(label),
    id: options.preview ? `copy-preview-net-label-${index}` : options.createId(),
    attachment: {
      wireId: copiedWireIds.get(label.attachment.wireId) ?? "",
      point: movePoint(label.attachment.point)
    }
  }));
  const notes = copyState.source.notes.map((note, index) => {
    const moved = movePoint(note);
    return {
      ...cloneNote(note),
      id: options.preview ? `copy-preview-note-${index}` : options.createId(),
      x: moved.x,
      y: moved.y
    };
  });
  const junctionAppearances = copyState.source.junctionAppearances.map((appearance) => ({
    ...cloneJunctionAppearance(appearance),
    point: movePoint(appearance.point)
  }));
  return {
    symbolTemplate: copyState.source.symbolTemplate,
    components,
    wires,
    inductorCouplings,
    connections: {
      ...cloneConnections(copyState.source.connections),
      wires: Object.fromEntries(Object.entries(copyState.source.connections.wires).flatMap(([id, nodes]) => {
        const next = copiedWireIds.get(id);
        return next ? [[next, [...nodes]]] : [];
      })),
      pins: Object.fromEntries(Object.entries(copyState.source.connections.pins).flatMap(([id, pins]) => {
        const next = copiedComponentIds.get(id);
        return next ? [[next, { ...pins }]] : [];
      }))
    },
    netLabels,
    notes,
    junctionAppearances: normalizeJunctionAppearances(junctionAppearances)
  };
}

export function rotateCopySourceAroundAnchor(copyState: CopyState | null) {
  if (!copyState || copySourceCount(copyState.source) === 0) return false;
  const anchor = snapPoint(copyState.anchor);
  const transformPoint = (point: Point) => {
    const local = { x: point.x - anchor.x, y: point.y - anchor.y };
    const rotated = rotatePoint(local, 90);
    return snapPoint({ x: anchor.x + rotated.x, y: anchor.y + rotated.y });
  };

  copyState.source.components.forEach((component) => {
    const next = transformPoint(component);
    component.x = next.x;
    component.y = next.y;
    component.rotation = (component.rotation + 90) % 360;
  });

  copyState.source.wires.forEach((wire) => {
    wire.points = normalizeWirePath(wire.points.map(transformPoint));
  });
  copyState.source.netLabels.forEach((label) => {
    label.attachment.point = transformPoint(label.attachment.point);
  });

  copyState.source.notes.forEach((note) => {
    transformNote(note, transformPoint, true);
  });

  copyState.source.junctionAppearances = normalizeJunctionAppearances(
    copyState.source.junctionAppearances.map((appearance) => ({
      ...appearance,
      point: transformPoint(appearance.point)
    }))
  );
  return true;
}

export function mirrorCopySourceAroundAnchor(copyState: CopyState | null, axis: "x" | "y") {
  if (!copyState || copySourceCount(copyState.source) === 0) return false;
  const anchor = snapPoint(copyState.anchor);
  const transformPoint = (point: Point) => {
    const local = { x: point.x - anchor.x, y: point.y - anchor.y };
    return axis === "x" ? snapPoint({ x: anchor.x - local.x, y: point.y }) : snapPoint({ x: point.x, y: anchor.y - local.y });
  };

  copyState.source.components.forEach((component) => {
    const next = transformPoint(component);
    component.x = next.x;
    component.y = next.y;
    if (axis === "x") {
      component.rotation = (360 - component.rotation) % 360;
    } else {
      component.rotation = (540 - component.rotation) % 360;
    }
    component.mirrored = !component.mirrored;
  });

  copyState.source.wires.forEach((wire) => {
    wire.points = normalizeWirePath(wire.points.map(transformPoint));
  });
  copyState.source.netLabels.forEach((label) => {
    label.attachment.point = transformPoint(label.attachment.point);
  });

  copyState.source.notes.forEach((note) => {
    transformNote(note, transformPoint, false);
  });

  copyState.source.junctionAppearances = normalizeJunctionAppearances(
    copyState.source.junctionAppearances.map((appearance) => ({
      ...appearance,
      point: transformPoint(appearance.point)
    }))
  );
  return true;
}

export function copySourceCount(source: CopySource) {
  return source.components.length
    + source.wires.length
    + (source.inductorCouplings?.length ?? 0)
    + source.netLabels.length
    + source.notes.length;
}

export function applyCopyPlacementToDocument(document: SchematicDocument, copied: CopySource): CopyPlacementResult {
  const count = copySourceCount(copied);
  if (count === 0) {
    return {
      count,
      ids: [],
      noteIds: [],
      status: "Nothing to copy.",
      placed: false
    };
  }

  const fresh = connectionIdFactory(document.connections);
  const identities = new Map<string, string>();
  const remap = (id: string) => {
    let next = identities.get(id);
    if (!next) { next = fresh(); identities.set(id, next); }
    return next;
  };
  Object.entries(copied.connections.wires).forEach(([id, nodes]) => { document.connections.wires[id] = nodes.map(remap); });
  Object.entries(copied.connections.pins).forEach(([id, pins]) => {
    document.connections.pins[id] = Object.fromEntries(Object.entries(pins).map(([pinId, node]) => [pinId, remap(node)]));
  });
  document.components.push(...copied.components);
  document.wires.push(...copied.wires);
  const copiedInductorCouplings = copied.inductorCouplings ?? [];
  if (copiedInductorCouplings.length > 0) {
    document.inductorCouplings = [
      ...(document.inductorCouplings ?? []),
      ...copiedInductorCouplings
    ];
  }
  document.netLabels.push(...copied.netLabels);
  document.notes.push(...copied.notes);
  if (copied.junctionAppearances.length) {
    document.junctionAppearances = normalizeJunctionAppearances([
      ...document.junctionAppearances,
      ...copied.junctionAppearances
    ]);
  }

  connectGeometry(document, {
    wireIds: new Set(copied.wires.map(wire => wire.id)),
    componentIds: new Set(copied.components.map(component => component.id)),
    preserveInternal: true
  });

  return {
    count,
    ids: [...copied.components.map((component) => component.id), ...copied.wires.map((wire) => wire.id), ...copied.netLabels.map((label) => label.id)],
    noteIds: copied.notes.map((note) => note.id),
    status: `Copied ${count} object${count === 1 ? "" : "s"}. Move to another point and click to copy again, or Esc cancels.`,
    placed: true
  };
}

function emptyCopySource(): CopySource {
  return {
    components: [],
    wires: [],
    inductorCouplings: [],
    netLabels: [],
    notes: [],
    connections: emptyConnections(),
    junctionAppearances: []
  };
}

function selectConnections(graph: SchematicConnections, components: Set<string>, wires: Set<string>): SchematicConnections {
  const selected: SchematicConnections = {
    wires: Object.fromEntries(Object.entries(graph.wires).filter(([id]) => wires.has(id)).map(([id, nodes]) => [id, [...nodes]])),
    pins: Object.fromEntries(Object.entries(graph.pins).filter(([id]) => components.has(id)).map(([id, pins]) => [id, { ...pins }]))
  };
  return selected;
}

function cloneComponent(component: ComponentInstance): ComponentInstance {
  return {
    ...component,
    values: { ...component.values },
    appearance: component.appearance ? { ...component.appearance } : undefined
  };
}

function cloneWire(wire: Wire): Wire {
  return {
    ...wire,
    points: clonePoints(wire.points),
    appearance: wire.appearance ? { ...wire.appearance } : undefined
  };
}

function cloneInductorCoupling(coupling: InductorCoupling): InductorCoupling {
  return {
    ...coupling,
    appearance: coupling.appearance ? { ...coupling.appearance } : undefined
  };
}

function cloneNote(note: SchematicNote): SchematicNote {
  return { ...note };
}

function cloneNetLabel(label: NetLabel): NetLabel {
  return {
    ...label,
    attachment: { wireId: label.attachment.wireId, point: { ...label.attachment.point } }
  };
}

function cloneJunctionAppearance(appearance: JunctionAppearance): JunctionAppearance {
  return {
    ...appearance,
    point: { ...appearance.point }
  };
}
