import type { ComponentInstance, ComponentType, InductorCoupling, JunctionAppearance, NetLabel, Point, SchematicConnections, SchematicDocument, SchematicNote, Wire } from "./types";
import {
  componentVisualBounds,
  netLabelVisualBounds,
  noteVisualBounds,
  unionRects,
  wireVisualBounds
} from "./view-geometry";
