export function localizeNetlistDiagnostic(text: string) {
  if (schematicLanguage() !== "zh") return text;
  const label = /^Label "(.*)": (.+)$/.exec(text);
  if (label) return `标签“${label[1]}”：${localizeSchematicStatus(label[2])}`;
  for (const [pattern, translation] of NETLIST_DIAGNOSTIC_PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, translation);
  }
  return text;
}
