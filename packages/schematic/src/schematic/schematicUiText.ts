export function localizeSchematicStatus(text: string) {
  if (schematicLanguage() !== "zh") return text;
  if (Object.hasOwn(STATUS_ZH, text)) return STATUS_ZH[text];
  for (const [pattern, translation] of STATUS_PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, translation);
  }
  return parameterLabel(text);
}

export function localizeAnalysisDiagnostic(text: string) {
  const port = /^Missing or invalid (inputP|inputN|outputP|outputN) net selection\.$/.exec(text);
  if (port && schematicLanguage() === "zh") {
    const names = { inputP: "输入 +", inputN: "输入 −", outputP: "输出 +", outputN: "输出 −" };
    return `缺少有效的 ${names[port[1] as keyof typeof names]} 网络选择。`;
  }
  return localizeSchematicStatus(text);
}

